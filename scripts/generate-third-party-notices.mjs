import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import {
  collectProductionPackages,
  getSourceConfiguration,
  repositoryRoot,
  sha256Buffer,
} from './compliance-lib.mjs';

const outputPath = join(repositoryRoot, 'THIRD_PARTY_NOTICES.md');
const packages = collectProductionPackages();
const sources = getSourceConfiguration();
const noobs = sources.components.find((component) => component.id === 'noobs');
const licenseGroups = new Map();

for (const dependency of packages) {
  for (const notice of dependency.noticeFiles) {
    if (!notice.text) continue;
    const normalizedText = notice.text
      .split('\n')
      .map((line) => line.trimEnd())
      .join('\n')
      .trimEnd();
    const hash = sha256Buffer(Buffer.from(normalizedText));
    const group = licenseGroups.get(hash) || {
      text: normalizedText,
      packages: new Set(),
    };
    group.packages.add(dependency.key);
    licenseGroups.set(hash, group);
  }
}

const lines = [
  '# Third-Party Notices',
  '',
  '<!-- Generated by scripts/generate-third-party-notices.mjs. Do not edit by hand. -->',
  '',
  'Lappen Recorder includes third-party software. The project license does not',
  'replace the licenses and copyright notices listed here. Source archives for',
  'the native GPL components are attached to every Lappen Recorder release.',
  '',
  '## Native recording components',
  '',
];

for (const component of sources.components) {
  lines.push(
    `### ${component.name} ${component.version}`,
    '',
    `- Source repository: ${component.repository}`,
    `- Source commit: \`${component.sourceCommit}\``,
    `- Release source archive: \`${component.archiveName}\``,
    '',
  );
}

lines.push(
  'OBS Studio and the GPL-enabled FFmpeg build are distributed under the GNU',
  'General Public License, version 2 or later. The shipped FFmpeg build enables',
  'GPL code and libx264. See the project `LICENSE`, the matching release source',
  'archives, and the upstream repositories for the complete terms and notices.',
  '',
  `The npm package metadata for \`noobs@${noobs.version}\` identifies LGPL-2.0, while the`,
  'linked OBS components are GPL-covered. Lappen Recorder therefore treats the',
  'combined native recording component as GPL-covered for distribution.',
  '',
  '## JavaScript and native package inventory',
  '',
  '| Package | Declared license | Repository |',
  '| --- | --- | --- |',
);

for (const dependency of packages) {
  const repository = dependency.repository
    ? `[source](${dependency.repository})`
    : '';
  lines.push(
    `| \`${dependency.key.replaceAll('|', '\\|')}\` | ${String(dependency.license).replaceAll('|', '\\|')} | ${repository} |`,
  );
}

lines.push('', '## Included license and notice texts', '');

const groups = [...licenseGroups.entries()].sort(([, a], [, b]) =>
  [...a.packages][0].localeCompare([...b.packages][0]),
);

for (const [hash, group] of groups) {
  lines.push(
    `### Notice ${hash.slice(0, 12)}`,
    '',
    `Applies to: ${[...group.packages]
      .sort()
      .map((name) => `\`${name}\``)
      .join(', ')}`,
    '',
    '```text',
    group.text.replaceAll('```', '``` '),
    '```',
    '',
  );
}

const generated = `${lines.join('\n').trim()}\n`;
if (process.argv.includes('--check')) {
  if (!existsSync(outputPath) || readFileSync(outputPath, 'utf8') !== generated) {
    console.error(
      'THIRD_PARTY_NOTICES.md is stale. Run npm run compliance:notices.',
    );
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputPath, generated);
  console.log(
    `Generated THIRD_PARTY_NOTICES.md for ${packages.length} production packages.`,
  );
}
